#!/usr/bin/env python3
"""embed.py — package WaveDrom JSON files for pages opened from file:// (where fetch() of local JSON is blocked).

  embed.py --var NAME key=a.json key2=b.json > data.js
      writes `window.NAME = { "key": {...}, "key2": {...} };` — load it with <script src="data.js"> and reference
      a model as <div data-wave="NAME.key">.
  embed.py --html page.html --placeholder '/*WAVE_DATA*/' [key=]a.json ... --out out.html
      replaces the placeholder (e.g. inside <script type="application/json">, the template.html flow) with the JSON.

The output has line breaks (one model per key, one signal per line, long "tv" lists wrapped); --compact writes one line.
"""
import argparse, json, os, sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # -I drops the script dir from sys.path
import wavejson  # noqa: E402


def load(specs):
    if len(specs) == 1 and '=' not in specs[0]:
        with open(specs[0], encoding='utf-8') as f:
            return json.load(f), False
    out = {}
    for s in specs:
        key, _, path = s.partition('=')
        with open(path, encoding='utf-8') as f:
            out[key] = json.load(f)
    return out, True


def text_of(data, keyed, compact):
    if compact:
        return json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    is_wave = lambda d: isinstance(d, dict) and isinstance(d.get('signal'), list)
    if keyed and all(is_wave(d) for d in data.values()):
        return wavejson.dumps_many(data)
    return wavejson.dumps(data) if is_wave(data) else json.dumps(data, ensure_ascii=False, indent=1)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('files', nargs='+', help='key=file.json (or a single file.json)')
    ap.add_argument('--var', help='global variable name for the .js output')
    ap.add_argument('--html', help='HTML file containing the placeholder')
    ap.add_argument('--placeholder', default='/*WAVE_DATA*/')
    ap.add_argument('--compact', action='store_true', help='one line, no spaces (smallest output)')
    ap.add_argument('--out', help='output file (default: stdout)')
    a = ap.parse_args()
    text = text_of(*load(a.files), a.compact).replace('</', '<\\/')
    if a.html:
        with open(a.html, encoding='utf-8') as f:
            page = f.read()
        if a.placeholder not in page:
            raise SystemExit(f'embed: placeholder {a.placeholder!r} not found in {a.html}')
        result = page.replace(a.placeholder, text, 1)
    else:
        result = f'/* generated by tools/embed.py — do not edit */\nwindow.{a.var or "WAVES"} = {text};\n'
    if a.out:
        with open(a.out, 'w', encoding='utf-8') as f:
            f.write(result)
    else:
        sys.stdout.write(result)


if __name__ == '__main__':
    main()
