#!/usr/bin/env python3
"""wavefwcat.py — wavefw/wavefw.js from wavefw/src/*.js (make wavefw): the files in their order, one scope.

The page needs one file and no build step, so wavefw.js stays committed; this only puts it together after a change
of a source file. Each source file starts with a comment that says what it holds: it is left out, the parts are
separated by a banner with the file's name. --check: exit 1 when wavefw.js is not what the sources give (smoke and
make check call it).

  python3 -I tools/wavefwcat.py [--check]
"""
import argparse, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.join(os.path.dirname(HERE), 'wavefw')
PARTS = ['model', 'vcd', 'paint', 'view', 'svg', 'boot']
HEAD = ('/* wavefw.js — WaveDrom-format waveform framework: parser, interactive canvas viewer (WaveView), static SVG (WaveSVG).\n'
        '   No dependencies, no build step, works from file://. See docs/USAGE.md (Formats) for the supported WaveDrom subset and extensions.\n'
        '   Generated by `make wavefw` from wavefw/src/{model,vcd,paint,view,svg,boot}.js (one scope): edit those, not this file. */\n')


def build() -> str:
    """The text of wavefw.js: HEAD, then each source file without its leading comment, under a banner."""
    out = [HEAD]
    for name in PARTS:
        with open(os.path.join(FW, 'src', name + '.js'), encoding='utf-8') as f:
            text = f.read()
        if text.startswith('/*'):
            text = text[text.index('*/') + 2:].lstrip('\n')
        out.append(f'/* ======================== src/{name}.js ======================== */\n' + text)
    return ''.join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='only compare: exit 1 when wavefw/wavefw.js is out of date')
    a = ap.parse_args()
    text, path = build(), os.path.join(FW, 'wavefw.js')
    with open(path, encoding='utf-8') as f:
        now = f.read()
    if a.check:
        if now != text:
            sys.exit('wavefwcat: wavefw/wavefw.js is not the concatenation of wavefw/src/*.js: run make wavefw')
        return
    if now != text:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
    print(f'wavefwcat: {len(PARTS)} files -> wavefw/wavefw.js ({len(text.splitlines())} lines)', file=sys.stderr)


if __name__ == '__main__':
    main()
