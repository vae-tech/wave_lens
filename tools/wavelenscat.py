#!/usr/bin/env python3
"""wavelenscat.py — wavelens/wavelens.js from wavelens/src/*.js (make wavelens): the files in their order, one scope.

The page needs one file and no build step, so wavelens.js stays committed; this only puts it together after a change
of a source file. Each source file starts with a comment that says what it holds: it is left out, the parts are
separated by a banner with the file's name. --check: exit 1 when wavelens.js is not what the sources give, or a line of
the sources (and of the plugins sva.js, bus.js) is longer than WIDTH columns (smoke and make check call it).

  python3 -I tools/wavelenscat.py [--check]
"""
import argparse, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.join(os.path.dirname(HERE), 'wavelens')
PARTS = ['model', 'vcd', 'paint', 'view', 'edit', 'diff', 'modules', 'fsm', 'log', 'svg', 'boot']
PLUGINS = ['sva.js', 'bus.js']
WIDTH = 160
HEAD = ('/* wavelens.js — WaveDrom-format waveform framework: parser, interactive canvas viewer (WaveView), static SVG (WaveSVG).\n'
        '   No dependencies, no build step, works from file://. See docs/USAGE.md (Formats) for the supported WaveDrom subset and extensions.\n'
        '   Generated by `make wavelens` from wavelens/src/{model,vcd,paint,view,edit,diff,modules,fsm,log,svg,boot}.js (one scope): edit those, not this file. */\n')


def build() -> str:
    """The text of wavelens.js: HEAD, then each source file without its leading comment, under a banner."""
    out = [HEAD]
    for name in PARTS:
        with open(os.path.join(FW, 'src', name + '.js'), encoding='utf-8') as f:
            text = f.read()
        if text.startswith('/*'):
            text = text[text.index('*/') + 2:].lstrip('\n')
        out.append(f'/* ======================== src/{name}.js ======================== */\n' + text)
    return ''.join(out)


def too_long() -> list:
    """'file:line: N columns' of every line of the sources and the plugins longer than WIDTH, or with a comment opener."""
    out = []
    for rel in [os.path.join('src', n + '.js') for n in PARTS] + PLUGINS:
        with open(os.path.join(FW, rel), encoding='utf-8') as f:
            lines = f.read().split('\n')
        out += [f'wavelens/{rel}:{i}: {len(ln)} columns' for i, ln in enumerate(lines, 1) if len(ln) > WIDTH]
        # inlined in a page's <script> (mkhtml.py), a comment opener there makes the HTML parser read past the script's end
        out += [f'wavelens/{rel}:{i}: "<' + '!--" in it (it breaks the page it is inlined in)' for i, ln in enumerate(lines, 1) if '<' + '!--' in ln]
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true',
                    help=f'only check: exit 1 when wavelens/wavelens.js is out of date or a source line is over {WIDTH} columns')
    a = ap.parse_args()
    text, path = build(), os.path.join(FW, 'wavelens.js')
    with open(path, encoding='utf-8') as f:
        now = f.read()
    if a.check:
        if now != text:
            sys.exit('wavelenscat: wavelens/wavelens.js is not the concatenation of wavelens/src/*.js: run make wavelens')
        long = too_long()
        if long:
            sys.exit('\n'.join(f'wavelenscat: {x} (at most {WIDTH})' for x in long))
        return
    if now != text:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
    print(f'wavelenscat: {len(PARTS)} files -> wavelens/wavelens.js ({len(text.splitlines())} lines)', file=sys.stderr)


if __name__ == '__main__':
    main()
