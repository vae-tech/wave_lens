"""tools/wavejson.py, embed.py, wavefwcat.py, mkhtml.py: the readable JSON, the data files, wavefw.js, the page."""
import json, os, re, unittest

from tests.unit import helpers as H
import wavejson as WJ
import wavefwcat


class WaveJson(unittest.TestCase):
    DOC = {'signal': [{'name': 'a', 'wave': '01'}, ['g', {'name': 'b', 'tv': [[i, '1'] for i in range(20)]}, ['h', {'name': 'c', 'same': 'g.b'}]]],
           'time': {'t0': 25000.0, 'cycle': 5.5}}

    def test_ints(self):
        self.assertEqual(WJ.ints({'a': [1.0, 2.5, {'b': 3.0}]}), {'a': [1, 2.5, {'b': 3}]})

    def test_tv_wrapped_and_reads_back(self):
        text = WJ.dumps(self.DOC)
        self.assertEqual(json.loads(text), WJ.ints(self.DOC))
        self.assertIn('"tv": [\n', text)
        self.assertEqual(text.count('[0, "1"]'), 1)

    def test_one_signal_per_line(self):
        lines = WJ.dumps(self.DOC).splitlines()
        self.assertTrue(any(l.strip() == '{"name": "a", "wave": "01"},' for l in lines))

    def test_count_nested_same(self):
        self.assertEqual(WJ.count(self.DOC['signal']), 3)

    def test_dumps_many(self):
        self.assertEqual(json.loads(WJ.dumps_many({'x': self.DOC, 'y': self.DOC}))['y']['time']['t0'], 25000)


class Embed(unittest.TestCase):
    def test_var_output(self):
        with H.tmp() as d:
            p = os.path.join(d, 'a.json')
            json.dump({'signal': [{'name': 'a', 'wave': '01'}], 'x': '</script>'}, open(p, 'w'))
            rc, out, err = H.run_tool('embed', '--var', 'W', f'k={p}')
        self.assertEqual(rc, 0, err)
        self.assertTrue(out.startswith('/* generated by tools/embed.py'))
        self.assertIn('window.W = {', out)
        self.assertIn('<\\/script>', out)

    def test_placeholder_missing(self):
        with H.tmp() as d:
            p, h = os.path.join(d, 'a.json'), os.path.join(d, 'p.html')
            json.dump({}, open(p, 'w')); open(h, 'w').write('<html></html>')
            rc, _, err = H.run_tool('embed', '--html', h, p)
        self.assertEqual((rc, 'placeholder' in err, 'Traceback' in err), (1, True, False))

    def test_missing_input_one_line(self):
        rc, _, err = H.run_tool('embed', 'k=nope.json')
        self.assertEqual((rc, err.strip()), (1, 'embed: no such file: nope.json'))


