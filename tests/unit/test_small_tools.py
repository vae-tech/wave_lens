class MkHtml(unittest.TestCase):
    def page(self, cfg, *args):
        with H.tmp() as d:
            c, out = os.path.join(d, 'c.json'), os.path.join(d, 'p.html')
            json.dump(cfg, open(c, 'w'))
            rc, _, err = H.run_tool('mkhtml', '--config', c, '--out', out, '--reproducible', *args)
            text = open(out, encoding='utf-8').read() if rc == 0 else None
        return rc, err, text

    CFG = {'waves': H.fixture('crlf'), 'exact': True, 'signals': 'tb.s,tb.b', 'config': {'theme': 'dark', 'sort': 'asc'},
           'views': {'v': {'title': 'one', 'config': {'dim': 0.5}}}}

    def test_three_layers_on_the_tool_side(self):
        rc, err, text = self.page(self.CFG, '--no-sva')
        self.assertEqual(rc, 0, err)
        self.assertIn('<html lang="en" data-theme="dark">', text)
        self.assertIn('window.WAVELENS_CONFIG = {"sort": "asc"};', text)              # the global layer, without the theme
        waves = json.loads(re.search(r'window\.WAVES = (\{.*?\n\});', text, re.S).group(1).replace('<\\/', '</'))
        self.assertEqual(waves['v']['config'], {'hscale': 1, 'dim': 0.5})           # the view's own layer

    def test_hostile_data(self):
        """"<!--<script>" or "</script>" in a name, a value, an enum label, the settings, the title: the page's JSON blocks
        have no "<" (it would end them, or make the parser swallow the page up to a later </script>)."""
        doc = {'signal': [{'name': '<!--<script>', 'wave': '==', 'data': ['</script><b>', 'x<!--y']}], 'config': {'hscale': 1},
               'head': {'text': '<!--<script> head'}}
        with H.tmp() as d:
            j, out = os.path.join(d, 'v.json'), os.path.join(d, 'p.html')
            with open(j, 'w') as f:
                json.dump(doc, f)
            rc, _, err = H.run_tool('mkhtml', f'k={j}', '--no-sva', '--title', '<!--<script> page', '--reproducible', '--out', out)
            with open(out, encoding='utf-8') as f:
                text = f.read()
        self.assertEqual(rc, 0, err)
        self.assertNotIn('<!--', text)
        waves = re.search(r'<script>\nwindow\.WAVES = (.*?);\n</script>', text, re.S).group(1)
        self.assertNotIn('<', waves)
        self.assertEqual(json.loads(waves)['k']['signal'], doc['signal'])

    def test_reproducible_bytes(self):
        a, b = self.page(self.CFG, '--no-sva')[2], self.page(self.CFG, '--no-sva')[2]
        self.assertEqual(a, b)

    def test_no_sva_leaves_the_engine_out(self):
        text = self.page(self.CFG, '--no-sva')[2]
        self.assertNotIn('window.SVA =', text)
        self.assertIn('WaveBus', text)   # bus.js is always there

    def test_unknown_setting_is_an_error(self):
        rc, err, _ = self.page({**self.CFG, 'config': {'rowHeigth': 20}}, '--no-sva')
        self.assertEqual(rc, 1)
        self.assertIn('rowHeigth (did you mean rowHeight?)', err)

    def test_missing_config_one_line(self):
        rc, _, err = H.run_tool('mkhtml', '--config', 'nope.json', '--out', os.devnull)
        self.assertEqual((rc, err.strip()), (1, 'mkhtml: no such file: nope.json'))

    def test_build_in_the_page(self):
        # the bar's version line: the page carries the commit of the checkout that made it; --reproducible: none (the bytes)
        import common
        b = common.build_info('mkhtml.py')
        if b is None:
            self.skipTest('not a git checkout')
        self.assertRegex(b['commit'], r'^[0-9a-f]{7,}$')
        with H.tmp() as d:
            c, out = os.path.join(d, 'c.json'), os.path.join(d, 'p.html')
            json.dump(self.CFG, open(c, 'w'))
            rc, _, err = H.run_tool('mkhtml', '--config', c, '--out', out, '--no-sva')
            self.assertEqual(rc, 0, err)
            text = open(out, encoding='utf-8').read()
        self.assertIn(f'"commit": "{b["commit"]}"', text)
        self.assertIn(f'<b>WaveLens</b>{common.version()} · ', text)
        rc, _, text = self.page(self.CFG, '--no-sva')
        self.assertNotIn('window.WAVELENS_BUILD =', text)

    def test_views_not_a_mapping_one_line(self):
        # "views" as a list (review V C7): what it should be, not a TypeError's traceback
        rc, err, _ = self.page({**self.CFG, 'views': [{'title': 'a'}]}, '--no-sva')
        self.assertEqual(rc, 1)
        self.assertIn('"views" is {"name": {settings}, …}, one entry per view (not a list)', err)
        self.assertNotIn('Traceback', err)


