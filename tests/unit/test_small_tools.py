class MkHtml(unittest.TestCase):
    def page(self, cfg, *args):
        with H.tmp() as d:
            c, out = os.path.join(d, 'c.json'), os.path.join(d, 'p.html')
            json.dump(cfg, open(c, 'w'))
            rc, _, err = H.run_tool('mkhtml', '--config', c, '--out', out, '--reproducible', *args)
            text = open(out, encoding='utf-8').read() if rc == 0 else None
        return rc, err, text

    CFG = {'waves': H.fixture('crlf'), 'exact': True, 'signals': 'tb.s,tb.b', 'config': {'theme': 'dark', 'sort': 'asc'},
           'views': {'v': {'title': 'one', 'config': {'dim': 0.5}}}}

    def test_three_layers_on_the_tool_side(self):
        rc, err, text = self.page(self.CFG, '--no-sva')
        self.assertEqual(rc, 0, err)
        self.assertIn('<html lang="en" data-theme="dark">', text)
        self.assertIn('window.WAVEFW_CONFIG = {"sort": "asc"};', text)              # the global layer, without the theme
        waves = json.loads(re.search(r'window\.WAVES = (\{.*?\n\});', text, re.S).group(1).replace('<\\/', '</'))
        self.assertEqual(waves['v']['config'], {'hscale': 1, 'dim': 0.5})           # the view's own layer

    def test_reproducible_bytes(self):
        a, b = self.page(self.CFG, '--no-sva')[2], self.page(self.CFG, '--no-sva')[2]
        self.assertEqual(a, b)

    def test_no_sva_leaves_the_engine_out(self):
        text = self.page(self.CFG, '--no-sva')[2]
        self.assertNotIn('window.SVA =', text)
        self.assertIn('WaveBus', text)   # bus.js is always there

    def test_unknown_setting_is_an_error(self):
        rc, err, _ = self.page({**self.CFG, 'config': {'rowHeigth': 20}}, '--no-sva')
        self.assertEqual(rc, 1)
        self.assertIn('rowHeigth (did you mean rowHeight?)', err)

    def test_missing_config_one_line(self):
        rc, _, err = H.run_tool('mkhtml', '--config', 'nope.json', '--out', os.devnull)
        self.assertEqual((rc, err.strip()), (1, 'mkhtml: no such file: nope.json'))


