#!/usr/bin/env python3
"""pack.py — the WebAssembly engine as a script for pages: sva_wasm.wasm, deflate-raw compressed and base64 encoded,
as window.WAVEFW_SVA_WASM = {"size": bytes, "deflate": "..."} (wavefw/sva.js unpacks it with DecompressionStream).
make sva-build writes wavefw/sva.wasm.js with it; the file is committed, so pages build without Rust.

  pack.py sva_wasm.wasm wavefw/sva.wasm.js
"""
import argparse, base64, os, sys, zlib

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument('wasm', help='sva_wasm.wasm (make sva-build: BUILD/sva-target/wasm32-unknown-unknown/wasm/)')
ap.add_argument('out', help='the script to write (wavefw/sva.wasm.js)')
a = ap.parse_args()
wasm, out = a.wasm, a.out
if not os.path.isfile(wasm):
    ap.error(f'no such file: {wasm} (make sva-build)')
with open(wasm, 'rb') as f:
    raw = f.read()
z = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
b64 = base64.b64encode(z.compress(raw) + z.flush()).decode()
with open(out, 'w', encoding='ascii', newline='\n') as f:
    f.write('/* wavefw/sva.wasm.js: the SVA engine (sva/wasm, docs/sva/STACK.md) as WebAssembly, deflate-raw + base64.\n'
            '   Generated by make sva-build (sva/wasm/pack.py) - do not edit. */\n')
    f.write(f'window.WAVEFW_SVA_WASM = {{"size": {len(raw)}, "deflate": "{b64}"}};\n')
print(f'pack: {len(raw)} B wasm -> {len(b64)} B base64 (deflate) -> {out}', file=sys.stderr)
